#!/bin/bash
#
# build-wifi-binaries.sh
#
# Compila los binarios nativos necesarios para el módulo Pixie Dust de AmWF
# (wpa_supplicant, wpa_cli, pixiewps) para una arquitectura Android ARM dada.
#
# Uso:
#   ./build-wifi-binaries.sh <arch>   # arch: arm64-v8a | armeabi-v7a
#
# Requisitos:
#   - Android NDK instalado (variable ANDROID_NDK o ANDROID_NDK_HOME)
#   - Fuente de wpa_supplicant en ../wpa_supplicant-2.6/ (ajustar WPA_DIR)
#   - Fuente de pixiewps en ../pixiewps-master/ (ajustar PIXIEWPS_DIR)
#
# Licencia: GPL-3.0-or-later (igual que AmWF)

set -euo pipefail

ARCH="${1:-}"
if [[ -z "$ARCH" ]]; then
    echo "Uso: $0 <arm64-v8a|armeabi-v7a>"
    exit 1
fi

ANDROID_NDK="${ANDROID_NDK:-${ANDROID_NDK_HOME:-/opt/android-sdk/ndk/27.0.12077973}}"
ANDROID_API="${ANDROID_API:-24}"
TOOLCHAIN="$ANDROID_NDK/toolchains/llvm/prebuilt/linux-x86_64"
SYSROOT="$TOOLCHAIN/sysroot"
export PATH="$TOOLCHAIN/bin:$PATH"

case "$ARCH" in
    arm64-v8a)
        TRIPLE="aarch64-linux-android"
        SUFFIX=""
        ;;
    armeabi-v7a)
        TRIPLE="armv7a-linux-androideabi"
        SUFFIX="_32"
        ;;
    *)
        echo "Arquitectura no soportada: $ARCH (usa arm64-v8a o armeabi-v7a)"
        exit 1
        ;;
esac

CC="${TRIPLE}${ANDROID_API}-clang"
AR="${TRIPLE}-ar"
STRIP="${TRIPLE}-strip"

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
ASSETS_DIR="$PROJECT_DIR/app/src/main/assets/wifi"
mkdir -p "$ASSETS_DIR"

# ---------------------------------------------------------------------------
# 1. pixiewps (GPL-3.0-or-later, wiire-a/pixiewps)
# ---------------------------------------------------------------------------
PIXIEWPS_DIR="${PIXIEWPS_DIR:-$SCRIPT_DIR/../pixiewps-master}"
if [[ -d "$PIXIEWPS_DIR" ]]; then
    echo "[pixiewps] Compilando para $ARCH ..."
    make -C "$PIXIEWPS_DIR" clean >/dev/null 2>&1 || true
    make -C "$PIXIEWPS_DIR" \
        CC="$CC" \
        CFLAGS="-O3 -DANDROID -fPIE -fPIC -I$SYSROOT/usr/include -I$SYSROOT/usr/include/$TRIPLE" \
        LDFLAGS="-pie -L$SYSROOT/usr/lib/$TRIPLE/$ANDROID_API" \
        LIBS="" \
        OPENSSL=0 \
        -j$(nproc)
    if [[ -f "$PIXIEWPS_DIR/pixiewps" ]]; then
        "$STRIP" "$PIXIEWPS_DIR/pixiewps"
        cp "$PIXIEWPS_DIR/pixiewps" "$ASSETS_DIR/pixiewps$SUFFIX"
        echo "[pixiewps] OK -> assets/wifi/pixiewps$SUFFIX"
    else
        echo "[pixiewps] ERROR: binario no generado"
        exit 1
    fi
else
    echo "[pixiewps] SALTADO: no se encontró $PIXIEWPS_DIR"
fi

# ---------------------------------------------------------------------------
# 2. wpa_supplicant y wpa_cli (BSD-3-Clause, w1.fi)
# ---------------------------------------------------------------------------
WPA_DIR="${WPA_DIR:-$SCRIPT_DIR/../wpa_supplicant-2.6}"
if [[ -d "$WPA_DIR" ]]; then
    echo "[wpa_supplicant] Compilando para $ARCH ..."
    cd "$WPA_DIR/wpa_supplicant"

    # Configuración mínima: WEXT (sin libnl) + ctrl_interface + WPS
    cp android.config .config 2>/dev/null || cp defconfig .config 2>/dev/null || true
    sed -i 's/^#CONFIG_DRIVER_NL80211=y/CONFIG_DRIVER_NL80211=y/' .config 2>/dev/null || true
    grep -q "^CONFIG_WPS=y" .config || echo "CONFIG_WPS=y" >> .config
    sed -i 's/^CONFIG_CTRL_IFACE_BINDER=y/# CONFIG_CTRL_IFACE_BINDER is not set/' .config 2>/dev/null || true

    rm -rf build
    mkdir -p build

    # Generar config.h desde .config
    echo "/* Autogenerated by build-wifi-binaries.sh */" > build/config.h
    echo "#ifndef WPA_CONFIG_H" >> build/config.h
    echo "#define WPA_CONFIG_H" >> build/config.h
    grep '^CONFIG_[A-Z_]*=y' .config | while read -r line; do
        name=$(echo "$line" | cut -d= -f1)
        echo "#define $name 1" >> build/config.h
    done
    echo "#endif" >> build/config.h

    mkdir -p private
    cat > private/android_filesystem_config.h << 'EOF'
#ifndef ANDROID_FILESYSTEM_CONFIG_H
#define ANDROID_FILESYSTEM_CONFIG_H
#define AID_ROOT 0
#define AID_SHELL 2000
#define AID_WIFI 2010
#define AID_DHCP 2011
#define AID_INET 3003
#define AID_KEYSTORE 2016
#endif
EOF

    make \
        CC="$CC" \
        AR="$AR" \
        STRIP="$STRIP" \
        CFLAGS="-I. -I../src -I../src/utils -I../src/common -I../src/crypto -I./private \
                -I$SYSROOT/usr/include -I$SYSROOT/usr/include/$TRIPLE -DANDROID \
                -fPIE -fPIC -O2 -w" \
        LDFLAGS="-pie -L$SYSROOT/usr/lib/$TRIPLE/$ANDROID_API" \
        -j$(nproc)

    if [[ -f wpa_supplicant ]]; then
        "$STRIP" wpa_supplicant
        cp wpa_supplicant "$ASSETS_DIR/wpa_supplicant$SUFFIX"
        echo "[wpa_supplicant] OK -> assets/wifi/wpa_supplicant$SUFFIX"
    else
        echo "[wpa_supplicant] ERROR: binario no generado"
    fi

    if [[ -f wpa_cli ]]; then
        "$STRIP" wpa_cli
        cp wpa_cli "$ASSETS_DIR/wpa_cli$SUFFIX"
        echo "[wpa_cli] OK -> assets/wifi/wpa_cli$SUFFIX"
    else
        echo "[wpa_cli] ADVERTENCIA: binario no generado (puede requerir ajuste de .config)"
    fi
else
    echo "[wpa_supplicant] SALTADO: no se encontró $WPA_DIR"
fi

echo "=== Hecho para $ARCH ==="
ls -la "$ASSETS_DIR/"